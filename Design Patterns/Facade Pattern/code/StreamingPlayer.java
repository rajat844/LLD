public class StreamingPlayer {
    public void on() {
        System.out.println("Streaming Player turned on");
    }

    public void play() {
        System.out.println("Playing the video");
    }

    public void pause() {
        System.out.println("Video is paused");
    }

    public void off() {
        System.out.println("Streaming Player turned off");
    }
}
