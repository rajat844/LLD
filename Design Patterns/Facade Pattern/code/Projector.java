public class Projector {
    public void on() {
        System.out.println("Projector turned on");
    }

    public void setAspectRatio(int width, int height) {
        System.out.println("Aspect Ratio set to : " + width + " X " + height);
    }

    public void off() {
        System.out.println("Projector turned off");
    }
}